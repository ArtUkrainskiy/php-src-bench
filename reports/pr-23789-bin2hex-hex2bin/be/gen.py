#!/usr/bin/env python3
# Cut the SIMD helpers of PR #23789 out of the PR sources and wrap them in a freestanding test program:
# random valid and invalid 32-character chunks for php_hex2bin_simd_chunk(), random and all-byte inputs for
# zend_bin2hex_simd(), each checked against a scalar reference.   gen.py <php-src tree> > harness.c
import re, sys

src = sys.argv[1]
string_c = open(f"{src}/ext/standard/string.c").read()
zstring_c = open(f"{src}/Zend/zend_string.c").read()

def cut(text, start):
    i = text.index(start)
    j = text.index("\n}\n", i) + 3
    return text[i:j]

hex2bin = cut(string_c, "static zend_never_inline bool php_hex2bin_simd_chunk(")
bin2hex = cut(zstring_c, "static zend_never_inline void zend_bin2hex_simd(")
bin2hex_impl = cut(zstring_c, "static zend_always_inline void zend_bin2hex_impl(")

print(r'''/* generated by gen.py from the PR #23789 sources; do not edit */
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#define zend_never_inline __attribute__((noinline))
#define zend_always_inline inline __attribute__((always_inline))
void *memcpy(void *d, const void *s, size_t n) { unsigned char *a = d; const unsigned char *b = s; while (n--) *a++ = *b++; return d; }
#include "zend_simd.h"
static const char zend_hexconvtab[] = "0123456789abcdef";
''')
print(bin2hex_impl)
print(bin2hex)
print(hex2bin)
print(r'''
static long sys3(long n, long a, long b, long c)
{
#if defined(__aarch64__)
	register long x8 __asm__("x8") = n, x0 __asm__("x0") = a, x1 __asm__("x1") = b, x2 __asm__("x2") = c;
	__asm__ volatile("svc 0" : "+r"(x0) : "r"(x8), "r"(x1), "r"(x2) : "memory");
	return x0;
#else
	long r;
	__asm__ volatile("syscall" : "=a"(r) : "a"(n), "D"(a), "S"(b), "d"(c) : "rcx", "r11", "memory");
	return r;
#endif
}
#if defined(__aarch64__)
# define SYS_WRITE 64
# define SYS_EXIT 93
#else
# define SYS_WRITE 1
# define SYS_EXIT 60
#endif
static size_t slen(const char *s) { size_t n = 0; while (s[n]) n++; return n; }
static void put(const char *s) { sys3(SYS_WRITE, 1, (long) s, (long) slen(s)); }
static void putn(unsigned long v) { char b[24]; int i = 23; b[i] = 0; do { b[--i] = '0' + v % 10; v /= 10; } while (v); put(b + i); }
static void puthex(const unsigned char *p, int n) { char b[3] = {0}; for (int i = 0; i < n; i++) { b[0] = "0123456789abcdef"[p[i] >> 4]; b[1] = "0123456789abcdef"[p[i] & 15]; put(b); put(i + 1 < n ? " " : "\n"); } }
static uint64_t st = 23789;
static uint32_t rnd(void) { st = st * 6364136223846793005ULL + 1442695040888963407ULL; return (uint32_t) (st >> 33); }
static int nib(unsigned char c) { if (c >= '0' && c <= '9') return c - '0'; if (c >= 'a' && c <= 'f') return c - 'a' + 10; if (c >= 'A' && c <= 'F') return c - 'A' + 10; return -1; }
/* volatile so that inputs are not constant-folded into the helpers */
static volatile unsigned char in_buf[64];

#if defined(__x86_64__)
__attribute__((force_align_arg_pointer))
#endif
void _start(void)
{
	static const char digits[] = "0123456789abcdefABCDEF";
	unsigned char in[32], out[16], ref[16];
	unsigned long ok = 0, wrong = 0, wrong_zero = 0, rejected = 0, accepted_bad = 0, bad_total = 0, b_ok = 0, b_wrong = 0;
	int shown = 0;

	for (int k = 0; k < 100000; k++) {
		for (int i = 0; i < 32; i++) in_buf[i] = digits[rnd() % 22];
		int bad = k % 2 ? -1 : (int) (rnd() % 32);
		if (bad >= 0) { unsigned char c; do c = rnd() & 0xff; while (nib(c) >= 0); in_buf[bad] = c; bad_total++; }
		for (int i = 0; i < 32; i++) in[i] = in_buf[i];
		for (int i = 0; i < 16; i++) { out[i] = 0xAA; ref[i] = (unsigned char) (nib(in[2 * i]) << 4 | nib(in[2 * i + 1])); }
		bool r = php_hex2bin_simd_chunk(out, in);
		if (bad >= 0) { if (r) accepted_bad++; continue; }
		if (!r) { rejected++; continue; }
		int same = 1;
		for (int i = 0; i < 16; i++) same &= out[i] == ref[i];
		int zero = 1;
		for (int i = 0; i < 16; i++) zero &= out[i] == 0;
		if (same) ok++; else { wrong++; wrong_zero += zero; if (shown++ < 2) { put("hex2bin wrong: in "); for (int i = 0; i < 32; i++) { char c[2] = {(char) in[i], 0}; put(c); } put("\n  got "); puthex(out, 16); put("  ref "); puthex(ref, 16); } }
	}
	put("hex2bin valid chunks: ok "); putn(ok); put(", wrong "); putn(wrong); put(" (all 16 bytes zero: "); putn(wrong_zero); put("), rejected "); putn(rejected);
	put("; invalid chunks: "); putn(bad_total); put(", accepted "); putn(accepted_bad); put("\n");

	char hx[512 + 32], hr[512 + 32];
	unsigned char bin[256];
	for (int k = 0; k < 2000; k++) {
		int n = k == 0 ? 256 : 16 + (int) (rnd() % 240);
		for (int i = 0; i < n; i++) in_buf[i % 64] = k == 0 ? (unsigned char) i : (unsigned char) rnd(), bin[i] = in_buf[i % 64];
		zend_bin2hex_simd(hx, bin, (size_t) n);
		zend_bin2hex_impl(hr, bin, (size_t) n, zend_hexconvtab);
		int same = 1;
		for (int i = 0; i < 2 * n; i++) same &= hx[i] == hr[i];
		if (same) b_ok++; else b_wrong++;
	}
	put("bin2hex inputs (first: all 256 byte values): ok "); putn(b_ok); put(", wrong "); putn(b_wrong); put("\n");
	sys3(SYS_EXIT, 0, 0, 0);
	for (;;) {}
}
''')
